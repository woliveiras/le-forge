import {test,expect} from '@playwright/test';
const headers={Authorization:'Bearer e2e-admin-token'};
test('reviews a pinned template upgrade and parameters without granting tools or enabling the connection',async({page})=>{
 await page.addInitScript(()=>localStorage.setItem('leforgeToken','e2e-admin-token'));
 await page.goto('/#/connections/connect?template=github&version=1');
 await page.getByRole('button',{name:'Use template defaults'}).click();
 await page.getByLabel('Connection ID',{exact:true}).fill('template-upgrade');
 await page.getByLabel('Connection name',{exact:true}).fill('Template upgrade');
 await page.getByLabel('Connection enabled',{exact:true}).uncheck();
 await page.getByRole('button',{name:'Save MCP connection',exact:true}).click();
 await expect(page).toHaveURL(/connections\/c\/template-upgrade\/overview$/);
 await page.getByRole('link',{name:'Settings',exact:true}).click();
 await page.getByRole('button',{name:'Edit Template upgrade',exact:true}).click();
 const read=async()=>{const response=await page.request.get('/api/v1/mcp/connections/template-upgrade',{headers});expect(response.ok()).toBeTruthy();return response.json();};
 const original=await read();
 await page.getByRole('button',{name:'Review template update to v2'}).click();
 await expect(page.getByRole('dialog',{name:'Review template update'})).toContainText('No tools are granted');
 await page.getByRole('button',{name:'Cancel template update'}).click();
 expect(await read()).toEqual(original);
 await page.getByRole('button',{name:'Review template update to v2'}).click();
 await page.getByRole('button',{name:'Apply update to draft'}).click();
 await page.getByLabel('Read-only toolset',{exact:true}).selectOption('repos');
 await page.getByRole('button',{name:'Apply Read-only toolset',exact:true}).click();
 await expect(page.getByLabel('MCP endpoint',{exact:true})).toHaveValue('https://api.githubcopilot.com/mcp/x/repos/readonly');
 expect(await read()).toEqual(original);
 await page.getByRole('button',{name:'Save MCP connection',exact:true}).click();
 await expect.poll(async()=>(await read()).template.version).toBe(2);
 const saved=await read();expect(saved.enabled).toBe(false);expect(saved.tools).toEqual([]);expect(saved.templateParameters).toEqual({toolset:'repos'});expect(saved.credentialConfigured).toBe(false);
 await page.reload();await expect(page.getByText('Template: github v2')).toBeVisible();
});

test('GitLab template reviews an instance and keeps authorization pending without contacting it',async({page})=>{
 await page.addInitScript(()=>localStorage.setItem('leforgeToken','e2e-admin-token'));
 await page.goto('/#/connections/connect?template=gitlab&version=1');
 await page.getByRole('button',{name:'Use template defaults'}).click();
 await page.getByLabel('GitLab instance URL',{exact:true}).fill('https://gitlab.fixture.example/path');
 await page.getByRole('button',{name:'Apply GitLab instance URL',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('HTTPS origin');
 await page.getByLabel('GitLab instance URL',{exact:true}).fill('https://gitlab.fixture.example');
 await page.getByRole('button',{name:'Apply GitLab instance URL',exact:true}).click();
 await expect(page.getByLabel('MCP endpoint',{exact:true})).toHaveValue('https://gitlab.fixture.example/api/v4/mcp');
 await expect(page.getByLabel('OAuth issuer',{exact:true})).toHaveValue('https://gitlab.fixture.example');
 await page.getByLabel('OAuth client ID',{exact:true}).fill('fixture-client');
 await page.getByLabel('Connection ID',{exact:true}).fill('gitlab-template-instance');
 await page.getByLabel('Connection enabled',{exact:true}).uncheck();
 await page.getByRole('button',{name:'Save MCP connection',exact:true}).click();
 await expect(page).toHaveURL(/connections\/c\/gitlab-template-instance\/overview$/);
 const response=await page.request.get('/api/v1/mcp/connections/gitlab-template-instance',{headers});expect(response.ok()).toBeTruthy();
 const saved=await response.json();expect(saved.templateParameters).toEqual({instance:'https://gitlab.fixture.example'});expect(saved.oauth.status).toBe('authorization_required');expect(saved.tools).toEqual([]);
});

